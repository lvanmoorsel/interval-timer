const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const root = path.resolve(__dirname, "..");
const source = fs.readFileSync(path.join(root, "app.js"), "utf8");
const model = source.slice(source.indexOf("const num ="), source.indexOf("// ---------- Opslag"));
const context = { URLSearchParams };
vm.createContext(context);
vm.runInContext(model, context);
const gym = context.normalize(JSON.parse(fs.readFileSync(path.join(root, "gym-example.json"))));
const phases = context.buildPhases(gym);
assert.equal(phases.filter(p => p.manual).length, 15);
assert.equal(phases.filter(p => p.type === "work" && !p.manual).length, 9);
assert.equal(phases[0].dur, 300);
assert.equal(phases.at(-1).dur, 120);
assert.equal(phases[1].manual, true);
assert.equal(phases[2].dur, 45);
assert.equal(phases[3].set, 2);
const entries = gym.exercises.flatMap(e => [1,2,3].map(n => `${e.name} set ${n}~${e.detail}`));
for (let n=1; n<=3; n++) for (const e of gym.finisher.exercises) entries.push(`${e.name} ${n}~${e.detail}`);
const converted = context.parseInput("#t=A9&w=30&r=45&e=" + entries.join("|"));
assert.equal(converted.type, "gym");
assert.equal(converted.exercises.length, 5);
assert.equal(converted.finisher.rounds, 3);
assert.equal(converted.finisher.exercises[0].name, "Farmer carry");
const interval = context.normalize({prepare:0, rounds:2, exercises:[{name:"A"},{name:"B"}]});
assert.equal(context.buildPhases(interval).filter(p=>p.type==="work").map(p=>p.name).join(","),"A,B,A,B");
assert.throws(()=>context.normalize({rounds:Infinity,exercises:[{name:"A"}]}));
console.log("PASS gym phases, legacy import, finisher order, intervals, input validation");
